"""HA integration, bridge and app store versions, client pin and archive checks.

The release version is the integration version. The bridge has its own version.
ha_app/ and ha_app_beta/ are store folders generated by prepare_ha_app.py from
bridge/ and app/. They stay frozen between a stable release PR and a beta cut,
because every main commit that changes them is an app update for users.
"""

import base64
import json
from pathlib import Path, PurePosixPath
import re
import subprocess
import tomllib
import zipfile

import package as packaging
import prepare_ha_app as app

REPOSITORY = "keesmod/ha-eufy-cam"
MANIFEST = "custom_components/eufy_viewer/manifest.json"
STORE = {"ha_app": "stable", "ha_app_beta": "beta"}
SLUGS = {"ha_app": "eufy_viewer_bridge", "ha_app_beta": "eufy_viewer_bridge_beta"}
CLIENT_PIN = re.compile(
    r"https://github\.com/keesmod/eufy-mega-client/releases/download/"
    r"v((?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)(?:-beta\.[1-9]\d*)?)"
    r"/keesmod-eufy-mega-client-\1\.tgz"
)
HEADING = re.compile(r"## \d+\.\d+\.\d+ - (?:Unreleased|\d{4}-\d{2}-\d{2})")
DATED = re.compile(r"## \d+\.\d+\.\d+ - \d{4}-\d{2}-\d{2}\n")
# package.json keys that never reach the shipped bridge.
BRIDGE_DEV_KEYS = ("version", "description", "devDependencies")
# Hand-edited app/ files that are presentation only.
APP_TEXT = ("README.md", "CHANGELOG.md")


def run(root, *args):
    return subprocess.check_output(args, cwd=root, text=True).strip()


def read_json(root, path):
    return json.loads((root / path).read_text())


class Tree:
    """Tracked files of the checkout (rev None) or of a commit."""

    def __init__(self, root, rev=None):
        self.root, self.rev = root, rev
        args = ("ls-files",) if rev is None else ("ls-tree", "-r", "--name-only", rev)
        self.paths = set(run(root, "git", *args, "-z").split("\0")) - {""}

    def read(self, path):
        if path not in self.paths:
            return None
        if self.rev is None:
            return (self.root / path).read_bytes()
        return subprocess.check_output(
            ["git", "show", self.rev + ":" + path], cwd=self.root
        )

    def json(self, path):
        data = self.read(path)
        return None if data is None else json.loads(data)

    def text(self, path):
        data = self.read(path)
        return "" if data is None else data.decode()

    def files(self, folder):
        return {
            p[len(folder) + 1 :]: self.read(p)
            for p in self.paths
            if p.startswith(folder + "/")
        }


def pep440(version):
    # uv lock records 0.8.47b1 for 0.8.47-beta.1.
    return version.replace("-beta.", "b")


def section(text, version):
    """Heading and text of the section for version's X.Y.Z part, or None."""
    import release

    match = re.search(
        r"^## "
        + re.escape(release.stable_part(version))
        + r"(?: [^\n]*)?\n.*?(?=^## |\Z)",
        text,
        re.M | re.S,
    )
    return match and match[0]


def changelog(root, version, path="CHANGELOG.md"):
    text = section((root / path).read_text(), version) or ""
    body = text.partition("\n")[2].strip()
    if len(body) < 20:
        raise ValueError("Missing substantive changelog entry in " + path)
    return body


def app_changelog(tree):
    # A commit from before app/ existed kept the canonical changelog in ha_app/.
    return tree.text(
        "app/CHANGELOG.md"
        if "app/CHANGELOG.md" in tree.paths
        else "ha_app/CHANGELOG.md"
    )


def discovered_configs(paths):
    """Tracked files that the Supervisor store reads as app configurations."""
    return {
        p
        for p in paths
        if PurePosixPath(p).name.startswith("config.")
        and PurePosixPath(p).suffix in (".json", ".yaml", ".yml")
        and not any(
            part.startswith(".") or part == "rootfs" for part in PurePosixPath(p).parts
        )
    }


def store_versions(tree):
    """{folder: config version} of the store folders, after the discovery guard."""
    import release

    configs = discovered_configs(tree.paths)
    folders = [f for f in STORE if f + "/config.json" in configs]
    if "ha_app" not in folders or configs != {f + "/config.json" for f in folders}:
        raise ValueError(
            "The app store may discover only ha_app/config.json and "
            "ha_app_beta/config.json, found: " + ", ".join(sorted(configs))
        )
    versions = {}
    for folder in folders:
        config = tree.json(folder + "/config.json")
        release.parse_version(config.get("version"))
        if config.get("slug") != SLUGS[folder]:
            raise ValueError(f"{folder}/config.json needs slug {SLUGS[folder]}")
        versions[folder] = config["version"]
    if release.is_prerelease(versions["ha_app"]):
        raise ValueError("ha_app is the stable app and needs a plain version")
    return versions


def client_pin(package):
    url = package["dependencies"]["@keesmod/eufy-mega-client"]
    match = CLIENT_PIN.fullmatch(url)
    if not match:
        raise ValueError("Mega dependency must pin the exact versioned GitHub release")
    return match[1], url


def metadata(root):
    import release

    key, beta = release.version_key, release.is_prerelease
    tree = Tree(root)
    version = read_json(root, MANIFEST)["version"]
    release.parse_version(version)
    project = tomllib.loads((root / "pyproject.toml").read_text())["project"]
    lock = tomllib.loads((root / "uv.lock").read_text())
    uv_project = [p for p in lock["package"] if p["name"] == project["name"]]
    if (
        pep440(project["version"]) != pep440(version)
        or len(uv_project) != 1
        or uv_project[0]["version"] != pep440(version)
    ):
        raise ValueError("Integration, pyproject and uv.lock versions must match")
    bridge = read_json(root, "bridge/package.json")
    bridge_version = bridge["version"]
    if not isinstance(bridge_version, str) or not release.VERSION.fullmatch(
        bridge_version
    ):
        raise ValueError("Invalid bridge version")
    package_lock = read_json(root, "bridge/package-lock.json")
    if any(
        p["version"] != bridge_version
        for p in (package_lock, package_lock["packages"][""])
    ):
        raise ValueError("Bridge package and lock versions must match")
    if "version" in read_json(root, "app/app_config.json"):
        raise ValueError(
            "Remove version from app/app_config.json. prepare_ha_app.py adds it"
        )
    stores = store_versions(tree)
    chain = [*stores.values(), bridge_version]
    if any(key(a) > key(b) for a, b in zip(chain, chain[1:])):
        raise ValueError("Versions must satisfy ha_app <= ha_app_beta <= bridge")
    if not beta(bridge_version) and bridge_version != stores["ha_app"]:
        raise ValueError(
            "A plain bridge version is a stable app release and must equal the "
            "ha_app version. Use an X.Y.Z-beta.N bridge version until the release PR"
        )
    if any(
        name == "node_modules/eufy-security-client"
        or name.endswith("/node_modules/eufy-security-client")
        or "eufy-security-client" in item.get("dependencies", {})
        for name, item in package_lock["packages"].items()
    ):
        raise ValueError("Retired legacy dependency remains in the package lock")
    shipped = ("bridge/src/", *(folder + "/src/" for folder in stores))
    for path in (p for p in tree.paths if p.startswith(shipped) and p.endswith(".ts")):
        if PurePosixPath(path).name in {"legacy-backend.ts", "sdk-compat.ts"} or (
            re.search(
                r"(?:from\s*|import\s*\(?)[\"']eufy-security-client(?:/|[\"'])",
                (root / path).read_text(),
            )
        ):
            raise ValueError("Retired legacy runtime remains in shipped source")
    client, url = client_pin(bridge)
    dependency = package_lock["packages"]["node_modules/@keesmod/eufy-mega-client"]
    if dependency["resolved"] != url or dependency["version"] != client:
        raise ValueError("Mega dependency must pin the exact versioned GitHub release")
    integrity = dependency["integrity"]
    if (
        not integrity.startswith("sha512-")
        or len(base64.b64decode(integrity[7:], validate=True)) != 64
    ):
        raise ValueError("Mega dependency requires SHA512 lockfile integrity")
    if beta(client) and not (beta(bridge_version) and beta(version)):
        raise ValueError("A beta client pin needs beta bridge and integration versions")
    resource_versions = re.findall(
        r"eufy-viewer-card\.js\?v=([0-9A-Za-z.-]+)", (root / "README.md").read_text()
    )
    if not resource_versions or any(
        not release.VERSION.fullmatch(v) or beta(v) or key(v) > key(version)
        for v in resource_versions
    ):
        raise ValueError(
            "README card resource examples need a plain version that is not above "
            "the integration version"
        )
    changelog(root, bridge_version, "app/CHANGELOG.md")
    return {
        "repository": REPOSITORY,
        "version": version,
        "bridge": bridge_version,
        "mega_client": client,
        "mega_url": url,
        "mega_integrity": integrity,
    }


def production_lock(lock):
    keys = (
        "version",
        "resolved",
        "integrity",
        "dependencies",
        "optionalDependencies",
        "engines",
        "link",
    )
    return {
        name: {key: value[key] for key in keys if key in value}
        for name, value in lock["packages"].items()
        if name and not value.get("dev")
    }


def app_sources(tree):
    """Canonical app files, with app_config.json parsed."""
    if "app/app_config.json" in tree.paths:
        files = tree.files("app")
        files["app_config.json"] = json.loads(files["app_config.json"])
        return files
    # Transition: before app/ existed, its files lived in the generated ha_app/.
    generated = {"ha_app/config.json", *("ha_app/" + n for n in app.BRIDGE_FILES)}
    files = {
        p[len("ha_app/") :]: tree.read(p)
        for p in tree.paths
        if p.startswith("ha_app/")
        and p not in generated
        and not p.startswith("ha_app/src/")
    }
    config = tree.json("ha_app/config.json")
    config.pop("version")
    files["app_config.json"] = config
    return files


def changed_paths(root, rev):
    return set(
        run(root, "git", "diff", "--no-renames", "--name-only", "-z", rev).split("\0")
    ) - {""}


def bridge_runtime_changed(paths, old, new):
    """Whether the shipped bridge or app container differs between the trees."""
    if any(
        p.startswith("bridge/src/")
        or p in ("bridge/Dockerfile", "bridge/tsconfig.json")
        for p in paths
    ):
        return True
    old_package, new_package = (
        {
            k: v
            for k, v in t.json("bridge/package.json").items()
            if k not in BRIDGE_DEV_KEYS
        }
        for t in (old, new)
    )
    if old_package != new_package or production_lock(
        old.json("bridge/package-lock.json")
    ) != production_lock(new.json("bridge/package-lock.json")):
        return True
    old_app, new_app = app_sources(old), app_sources(new)
    return any(
        old_app.get(name) != new_app.get(name)
        for name in old_app.keys() | new_app.keys()
        if name not in APP_TEXT
    )


def runtime(paths, old, new):
    """(integration, bridge) runtime changes between two trees."""
    bridge = bridge_runtime_changed(paths, old, new)
    integration = bridge or any(
        p.startswith("custom_components/eufy_viewer/") for p in paths
    )
    return integration, bridge


def runtime_changed(root, rev):
    """Whether the integration runtime set differs between rev and the checkout."""
    return runtime(changed_paths(root, rev), Tree(root, rev), Tree(root))[0]


def following(version, closed=False):
    """The next candidate after version, per the release convention."""
    import release

    major, minor, patch, beta = release.parse_version(version)
    if beta is None or closed:
        return f"{major}.{minor}.{patch + 1}-beta.1"
    return f"{major}.{minor}.{patch}-beta.{beta + 1}"


def published(version):
    import release

    return release.published(release.GitHub(REPOSITORY), version)


def check_release(root, meta):
    """Version relations for a requested release, a release PR and a beta cut.

    Store bytes are compared only when a pull request changes a store folder.
    """
    import release

    key, beta = release.version_key, release.is_prerelease
    stores = store_versions(Tree(root))
    bridge = meta["bridge"]
    if beta(meta["version"]):
        if key(bridge) > key(stores["ha_app"]) and stores.get("ha_app_beta") != bridge:
            raise ValueError(
                f"Bridge {bridge} is newer than the stable app. Cut ha_app_beta at "
                f"{bridge} with prepare_ha_app.py --beta before the prerelease"
            )
        return
    if beta(bridge):
        raise ValueError("A stable release needs a plain bridge version")
    if any(v != bridge for v in stores.values()):
        raise ValueError(
            f"A stable release needs every store folder at bridge {bridge}. "
            "Run prepare_ha_app.py --release"
        )
    if beta(meta["mega_client"]):
        raise ValueError("A stable release needs a stable client pin")
    for path, version in (
        ("CHANGELOG.md", meta["version"]),
        ("app/CHANGELOG.md", bridge),
    ):
        if not DATED.match(section((root / path).read_text(), version) or ""):
            raise ValueError(f"Date the {version} heading in {path} for the release")
    if set(
        re.findall(
            r"eufy-viewer-card\.js\?v=([0-9A-Za-z.-]+)",
            (root / "README.md").read_text(),
        )
    ) != {meta["version"]}:
        raise ValueError("README card resource examples need the release version")


def check_changes(root, base, meta):
    import release

    key, beta = release.version_key, release.is_prerelease
    old, new = Tree(root, base), Tree(root)
    if old.read("repository.yaml") != new.read("repository.yaml"):
        raise ValueError("repository.yaml is the store identity and cannot change")
    version, bridge = meta["version"], meta["bridge"]
    old_version = old.json(MANIFEST)["version"]
    old_bridge = old.json("bridge/package.json")["version"]
    old_client = client_pin(old.json("bridge/package.json"))[0]
    old_stores, stores = store_versions(old), store_versions(new)
    for name, current, previous in (
        ("Integration", version, old_version),
        ("Bridge", bridge, old_bridge),
        ("Client pin", meta["mega_client"], old_client),
        *((folder, stores.get(folder), v) for folder, v in old_stores.items()),
    ):
        if current is None:
            raise ValueError(f"Store folder {name} cannot be removed")
        if key(current) < key(previous):
            raise ValueError(f"{name} version cannot go below base version {previous}")
    paths = changed_paths(root, base)
    integration_changed, bridge_changed = runtime(paths, old, new)
    changed_stores = [f for f in STORE if any(p.startswith(f + "/") for p in paths)]
    for folder in changed_stores:
        if stores.get(folder) in (None, old_stores.get(folder)):
            raise ValueError(
                f"{folder} is frozen. Only prepare_ha_app.py may change it, with a "
                "new version, in a stable release PR or a beta cut"
            )
        if stores[folder] != bridge:
            raise ValueError(f"{folder} must be generated at bridge version {bridge}")
        if new.files(folder) != app.render(root, STORE[folder], bridge):
            raise ValueError(f"{folder} differs from the prepare_ha_app.py output")
    if "ha_app" in changed_stores and (beta(bridge) or beta(version)):
        raise ValueError(
            "ha_app changes only in a stable release PR with plain bridge and "
            "integration versions"
        )
    release_pr = version != old_version and not beta(version)
    if release_pr or changed_stores:
        check_release(root, meta)
    old_notes, new_notes = old.text("CHANGELOG.md"), new.text("CHANGELOG.md")
    old_app_notes, new_app_notes = app_changelog(old), app_changelog(new)
    for path, before, after in (
        ("CHANGELOG.md", old_notes, new_notes),
        ("app/CHANGELOG.md", old_app_notes, new_app_notes),
    ):
        added = set(re.findall(r"^## .*$", after, re.M)) - set(
            re.findall(r"^## .*$", before, re.M)
        )
        for heading in sorted(added):
            if not HEADING.fullmatch(heading):
                raise ValueError(
                    f"New {path} headings use '## X.Y.Z - Unreleased' or "
                    f"'## X.Y.Z - YYYY-MM-DD', not '{heading}'"
                )
    stable = release.stable_part(version)
    if integration_changed and version == old_version:
        if DATED.match(section(old_notes, version) or ""):
            raise ValueError(
                f"The {stable} batch is closed by its release PR. "
                f"Raise the version to {following(version, closed=True)}"
            )
        if not beta(version):
            raise ValueError(
                "Runtime changes need an unpublished X.Y.Z-beta.N version. "
                f"Raise the version to {following(version)}"
            )
    if integration_changed and section(new_notes, version) == section(
        old_notes, version
    ):
        raise ValueError(
            f"Runtime changes need release notes in the CHANGELOG.md {stable} section"
        )
    if bridge_changed:
        top = max(old_stores.values(), key=key)
        if key(bridge) <= key(top):
            raise ValueError(
                f"Bridge runtime changes need a bridge version above the store "
                f"version {top}. Raise the bridge to {following(top)}"
            )
        if section(new_app_notes, bridge) == section(old_app_notes, bridge):
            raise ValueError(
                "Bridge runtime changes need release notes in the app/CHANGELOG.md "
                + release.stable_part(bridge)
                + " section"
            )
    # Network checks run last. A changed client pin must be a verified release.
    if meta["mega_client"] != old_client:
        import bump_client

        verified = bump_client.verify(meta["mega_client"])
        if (meta["mega_url"], meta["mega_integrity"]) != (
            verified["url"],
            verified["integrity"],
        ):
            raise ValueError("The client pin differs from the verified client release")
    # A version above base is unpublished by construction, because main's
    # version is at least every published version. Only an unchanged version
    # needs the lookup.
    if (
        version == old_version
        and (integration_changed or changed_stores)
        and published(version)
    ):
        raise ValueError(
            f"Version {version} is published. Raise the version to {following(version)}"
        )


def asset_names(meta):
    return [
        f"eufy-viewer-integration-{meta['version']}.zip",
        f"eufy-viewer-bridge-{meta['bridge']}.zip",
        f"ha-eufy-cam-source-{meta['version']}.zip",
    ]


def verify_archives(folder, meta):
    root = Path(__file__).resolve().parents[1]
    for name, expected in packaging.members(root).items():
        with zipfile.ZipFile(folder / name) as archive:
            names = archive.namelist()
            if len(names) != len(set(names)) or set(names) != expected:
                raise ValueError("Unexpected or missing files in " + name)
            for path in names:
                if archive.read(path) != (root / path).read_bytes():
                    raise ValueError("Archive differs from checked source: " + path)


def build(root, folder):
    packaging.build(folder, root)
    verify_archives(folder, metadata(root))
